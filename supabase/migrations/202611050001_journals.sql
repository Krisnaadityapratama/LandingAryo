CREATE TABLE IF NOT EXISTS public.banks (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  account_number TEXT NOT NULL DEFAULT '',
  account_holder TEXT NOT NULL DEFAULT '',
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.journals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  voucher_no TEXT NOT NULL UNIQUE,
  kos TEXT NOT NULL,
  post_date DATE NOT NULL,
  user_remark TEXT NOT NULL DEFAULT '',
  total_debit NUMERIC(18, 2) NOT NULL,
  total_credit NUMERIC(18, 2) NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  CONSTRAINT journals_balanced CHECK (total_debit = total_credit)
);

CREATE INDEX IF NOT EXISTS idx_journals_post_date
  ON public.journals (post_date DESC, id DESC);

CREATE TABLE IF NOT EXISTS public.journal_lines (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  journal_id BIGINT NOT NULL REFERENCES public.journals(id) ON DELETE CASCADE,
  account_name TEXT NOT NULL,
  bank_id BIGINT REFERENCES public.banks(id) ON DELETE RESTRICT,
  line_remark TEXT NOT NULL DEFAULT '',
  debit NUMERIC(18, 2) NOT NULL DEFAULT 0 CHECK (debit >= 0),
  credit NUMERIC(18, 2) NOT NULL DEFAULT 0 CHECK (credit >= 0),
  CONSTRAINT journal_lines_one_side CHECK (
    (debit > 0 AND credit = 0) OR (credit > 0 AND debit = 0)
  )
);

CREATE INDEX IF NOT EXISTS idx_journal_lines_journal_id
  ON public.journal_lines (journal_id, id);

CREATE TABLE IF NOT EXISTS public.journal_voucher_counters (
  period TEXT PRIMARY KEY CHECK (period ~ '^[0-9]{4}$'),
  last_number INTEGER NOT NULL CHECK (last_number > 0)
);

ALTER TABLE public.banks ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.journals ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.journal_lines ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.journal_voucher_counters ENABLE ROW LEVEL SECURITY;

CREATE OR REPLACE FUNCTION public.create_journal(
  p_kos TEXT,
  p_post_date DATE,
  p_user_remark TEXT,
  p_lines JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_period TEXT;
  v_number INTEGER;
  v_voucher TEXT;
  v_journal_id BIGINT;
  v_line JSONB;
  v_account_name TEXT;
  v_bank_id BIGINT;
  v_debit NUMERIC(18, 2);
  v_credit NUMERIC(18, 2);
  v_total_debit NUMERIC(18, 2) := 0;
  v_total_credit NUMERIC(18, 2) := 0;
  v_line_count INTEGER := 0;
BEGIN
  IF NULLIF(BTRIM(p_kos), '') IS NULL OR p_post_date IS NULL THEN
    RAISE EXCEPTION 'Kos and post date are required';
  END IF;

  IF p_lines IS NULL OR jsonb_typeof(p_lines) <> 'array'
     OR jsonb_array_length(p_lines) < 2 OR jsonb_array_length(p_lines) > 100 THEN
    RAISE EXCEPTION 'Journal must have between 2 and 100 lines';
  END IF;

  FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines)
  LOOP
    v_account_name := NULLIF(BTRIM(v_line->>'account_name'), '');
    v_debit := COALESCE(NULLIF(v_line->>'debit', '')::NUMERIC, 0);
    v_credit := COALESCE(NULLIF(v_line->>'credit', '')::NUMERIC, 0);

    IF v_account_name IS NULL OR v_debit < 0 OR v_credit < 0
       OR (v_debit > 0 AND v_credit > 0)
       OR (v_debit = 0 AND v_credit = 0) THEN
      RAISE EXCEPTION 'Invalid journal line';
    END IF;

    v_total_debit := v_total_debit + v_debit;
    v_total_credit := v_total_credit + v_credit;
    v_line_count := v_line_count + 1;
  END LOOP;

  IF v_line_count < 2 OR v_total_debit <= 0 OR v_total_debit <> v_total_credit THEN
    RAISE EXCEPTION 'Journal debit and credit totals must be equal and greater than zero';
  END IF;

  v_period := TO_CHAR(p_post_date, 'YYMM');
  INSERT INTO public.journal_voucher_counters (period, last_number)
  VALUES (v_period, 1)
  ON CONFLICT (period) DO UPDATE
    SET last_number = public.journal_voucher_counters.last_number + 1
  RETURNING last_number INTO v_number;

  v_voucher := 'JV' || v_period || LPAD(v_number::TEXT, GREATEST(3, LENGTH(v_number::TEXT)), '0');

  INSERT INTO public.journals (
    voucher_no, kos, post_date, user_remark, total_debit, total_credit
  )
  VALUES (
    v_voucher,
    BTRIM(p_kos),
    p_post_date,
    COALESCE(p_user_remark, ''),
    v_total_debit,
    v_total_credit
  )
  RETURNING id INTO v_journal_id;

  FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines)
  LOOP
    v_bank_id := NULLIF(v_line->>'bank_id', '')::BIGINT;
    INSERT INTO public.journal_lines (
      journal_id, account_name, bank_id, line_remark, debit, credit
    )
    VALUES (
      v_journal_id,
      BTRIM(v_line->>'account_name'),
      v_bank_id,
      COALESCE(v_line->>'line_remark', ''),
      COALESCE(NULLIF(v_line->>'debit', '')::NUMERIC, 0),
      COALESCE(NULLIF(v_line->>'credit', '')::NUMERIC, 0)
    );
  END LOOP;

  RETURN jsonb_build_object(
    'id', v_journal_id,
    'voucher_no', v_voucher,
    'kos', BTRIM(p_kos),
    'post_date', p_post_date,
    'user_remark', COALESCE(p_user_remark, ''),
    'total_debit', v_total_debit,
    'total_credit', v_total_credit
  );
END;
$$;

REVOKE ALL ON FUNCTION public.create_journal(TEXT, DATE, TEXT, JSONB) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.create_journal(TEXT, DATE, TEXT, JSONB) FROM anon, authenticated;
GRANT EXECUTE ON FUNCTION public.create_journal(TEXT, DATE, TEXT, JSONB) TO service_role;
GRANT ALL ON public.banks, public.journals, public.journal_lines,
  public.journal_voucher_counters TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public.banks_id_seq TO service_role;
